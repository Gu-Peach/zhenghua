"""Generate the Server's public DTO adapter from Agent models, without running an Agent."""

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
source = ROOT / "services/agent/src/agent/explain_agent/models.py"
target = ROOT / "services/server/src/wiring_server/explain_contract.py"
names = {
    "RescanTargetBinding",
    "RescanRemovedRow", "RescanReplacement",
    "RescanScope",
    "RescanEvidenceImage",
    "RescanRequest", "RescanAsset", "RescanUpload", "RescanFields", "RescanChange", "RescanCandidate", "RescanRun", "RescanDecision",
    "EditScope",
    "RemoveTerminalPrefix",
    "SwapEndpoints",
    "ConnectionFieldValues",
    "SetConnectionFields",
    "ConnectionEditRequest",
    "ConnectionEditChange",
    "ConnectionEditProposal",
    "ConnectionEditDecision",
    "ConnectionEditReceipt",
    "ConnectionQuery",
    "ExplainTurn",
    "TerminalPosition",
    "ConnectionFacts",
    "ProfileEvidence",
    "DrawingEvidence",
    "EvidenceStep",
    "ExplainContext",
    "SearchResult",
    "SearchCoverage",
    "ExplainResponse",
    "ToolActivity",
    "ExplainEvent",
}
text = source.read_text(encoding="utf-8")
parts = []
for node in ast.parse(text).body:
    if isinstance(node, ast.ClassDef) and node.name in names:
        parts.append(ast.get_source_segment(text, node))
    if isinstance(node, ast.Assign) and any(
        isinstance(t, ast.Name) and t.id == "ExactText" for t in node.targets
    ):
        parts.append(ast.get_source_segment(text, node))
header = """# Generated by services/agent/scripts/export_explain_contract.py; do not edit by hand.
from __future__ import annotations

from typing import Annotated, Any, Literal
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field, model_validator


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid", validate_assignment=True)
"""
target.write_text(header + "\n\n\n" + "\n\n\n".join(parts) + "\n", encoding="utf-8")
print(target)
