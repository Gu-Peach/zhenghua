ROOT = Path(__file__).resolve().parents[3]
BASE = ROOT / "services/agent/src/agent/profile_agent"
names = {
    "TemplateFields",
    "ImageUse",
    "ExampleCase",
    "DraftCreate",
    "Attachment",
    "DraftView",
    "TargetImage",
    "StageGenerate",
    "StageCandidate",
    "StageConfirm",
    "WizardState",
    "CaseReading",
    "ConversationTurn",
    "ConversationMessage",
    "ConversationState",
    "ConversationEvent",
    "PdfSampleRequest",
    "SampledPdfPage",
    "PdfSampleInfo",
    "PdfSampleResult",
    "FileEdit",
    "EvidenceAnchor",
    "Finding",
    "ProposalRequest",
    "FileDiff",
    "Proposal",
    "ProfileTurn",
    "ValidationIssue",
    "ValidationReport",
    "ProfileReply",
    "ProfileEvent",
    "ProfileImport",
    "EditFilesInput",
    "EditText",
    "EditImage",
    "EditPackage",
    "ProfileEditState",
}
parts = [
    """# Generated by services/agent/scripts/export_profile_contract.py; do not edit.
from __future__ import annotations

from typing import Any, Literal
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class StrictModel(BaseModel):
    model_config = ConfigDict(extra='forbid', validate_assignment=True)

Stage = Literal['classification', 'scan', 'completion']
"""
]
for file in ("models.py", "wizard.py", "conversation.py"):
    source = (BASE / file).read_text(encoding="utf-8")
    for node in ast.parse(source).body:
        if isinstance(node, ast.ClassDef) and node.name in names:
            parts.append(ast.get_source_segment(source, node) or "")
target = ROOT / "services/server/src/wiring_server/profile_contract.py"
target.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
print(target)
